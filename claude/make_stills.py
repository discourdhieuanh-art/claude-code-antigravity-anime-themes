#!/usr/bin/env python3
"""Rebuild the pixel-art stills of the Claude pixel themes (method 2: denoise, contrast, colour, sharpen,
Lanczos to 160x90, libimagequant palette). Writes the still modules into the theme-examples-default plugin.
Usage: python3 make_stills.py   (frames in ./frames or $FRAMES, previews in ./preview; writes into ./plugin or $SCENES)"""
import html, json, os
from PIL import Image, ImageEnhance, ImageFilter

HERE = os.path.dirname(os.path.abspath(__file__))
FRAMES = os.environ.get('FRAMES', os.path.join(HERE, 'frames'))
SCENES = os.environ.get('SCENES', os.path.join(HERE, 'plugin', 'theme-examples-default', 'hooks', 'scenes'))
W, H, LIMIT = 160, 90, 131072

def prep(im):
    im = im.filter(ImageFilter.MedianFilter(3))
    im = ImageEnhance.Contrast(im).enhance(1.15)
    im = ImageEnhance.Color(im).enhance(1.25)
    return im.filter(ImageFilter.UnsharpMask(radius=2, percent=120, threshold=2))

def cover(im, w, h, cx=0.5):
    """Crop to w:h around horizontal centre cx (0..1), full height when wider."""
    sw, sh = im.size
    if sw / sh > w / h:
        cw = int(sh * w / h); x0 = max(0, min(sw - cw, int(cx * sw - cw / 2)))
        return im.crop((x0, 0, x0 + cw, sh))
    ch = int(sw * h / w); y0 = (sh - ch) // 2
    return im.crop((0, y0, sw, y0 + ch))

def single(path):
    return prep(cover(Image.open(path).convert('RGB'), W, H)).resize((W, H), Image.LANCZOS)

def duo(a, ca, b, cb):
    L = prep(cover(Image.open(a).convert('RGB'), 80, 90, ca)).resize((80, 90), Image.LANCZOS)
    R = prep(cover(Image.open(b).convert('RGB'), 80, 90, cb)).resize((80, 90), Image.LANCZOS)
    im = Image.new('RGB', (W, H)); im.paste(L, (0, 0)); im.paste(R, (80, 0))
    for x in range(77, 83):  # soften the seam
        t = (x - 77) / 5
        for y in range(H):
            l = L.getpixel((min(x, 79), y)); r = R.getpixel((max(x - 80, 0), y))
            im.putpixel((x, y), tuple(int(l[i] * (1 - t) + r[i] * t) for i in range(3)))
    return im

def to_svg(im, title):
    for k in (32, 30, 28, 26, 24):
        q = im.convert('RGBA').quantize(colors=k, method=Image.Quantize.LIBIMAGEQUANT)
        pal = q.getpalette(); px = q.load(); runs = {}
        for y in range(H):
            x = 0
            while x < W:
                c = px[x, y]; x0 = x
                while x < W and px[x, y] == c: x += 1
                runs.setdefault(c, []).append(f'M{x0} {y}h{x-x0}v1h-{x-x0}z')
        body = ''.join(f'<path fill="#{pal[c*3]:02x}{pal[c*3+1]:02x}{pal[c*3+2]:02x}" d="{"".join(v)}"/>' for c, v in runs.items())
        svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice" '
               f'shape-rendering="crispEdges"><title>{html.escape(title)}</title>{body}</svg>')
        if len(svg) <= LIMIT:
            return svg, k, q
    raise SystemExit(f'{title}: too big even at 24 colours')

F = lambda n: os.path.join(FRAMES, n)
JOBS = [
    ('whale', 'Moonlit Whale (Pixel)', single(F('whale-single.png'))),
    ('snow', 'Snow & Moon (Pixel)', duo(F('full-wallpapergeminichan.png'), 0.47, F('full-whale-moon-loop.png'), 0.42)),
    ('sea', 'Sea Dream (Pixel)', duo(F('full-whale-underwater-loop.png'), 0.5, F('full-furina-bg.png'), 0.62)),
    ('blade', 'Blade Duet (Pixel)', duo(F('full-boot-claude-loop.png'), 0.53, F('full-boot-antigravity-loop.png'), 0.6)),
]
os.makedirs(os.path.join(HERE, 'preview'), exist_ok=True)
out = {}
for key, title, im in JOBS:
    svg, k, q = to_svg(im, title)
    out[key] = svg
    q.convert('RGB').resize((W * 5, H * 5), Image.NEAREST).save(os.path.join(HERE, 'preview', f'{key}.png'))
    print(f'{title}: {k} colours, {len(svg)} chars')

HEAD = ('// Generated by claude/make_stills.py (method 2: denoise, contrast, colour, sharpen,\n'
        '// libimagequant palette). Frames of the Antigravity theme videos: fan art of others, personal use only.\n'
        '// Do not edit by hand.\n')
with open(os.path.join(SCENES, 'whale-moon-pixel', 'still.ts'), 'w') as f:
    f.write(HEAD + '\n/** The still picture of Moonlit Whale (Pixel), as Svg source: under the shader, and alone where it does not play. */\n'
            f'export function whaleMoonPixelSvg(): string {{\n  return {json.dumps(out["whale"])}\n}}\n')
with open(os.path.join(SCENES, 'pixel-duo', 'stills.ts'), 'w') as f:
    f.write(HEAD)
    for key, fn, what in (('snow', 'duoSnowMoonSvg', 'Snow & Moon: Gemini-chan beside the whale girl under the moon'),
                          ('sea', 'duoSeaDreamSvg', 'Sea Dream: the whale maid underwater beside Furina'),
                          ('blade', 'duoTwinBladesSvg', 'Blade Duet: the Claude sword girl beside the Gemini twin-blade girl')):
        f.write(f'\n/** {what}. */\nexport function {fn}(): string {{\n  return {json.dumps(out[key])}\n}}\n')
